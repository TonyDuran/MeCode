def ints(s):
    return list(map(int, s.split()))

def row(a):
    return " ".join(map(str, a))

def fmt(*lines):
    return "\n".join(str(x) for x in lines) + "\n"


def s_lantern(inp):
    s = inp.rstrip("\n")
    i, j = 0, len(s) - 1
    while i < j:
        if not s[i].isalnum():
            i += 1
        elif not s[j].isalnum():
            j -= 1
        else:
            if s[i].lower() != s[j].lower():
                return "NO\n"
            i += 1
            j -= 1
    return "YES\n"


sys.stdout.write(s_lantern(sys.stdin.read()))
